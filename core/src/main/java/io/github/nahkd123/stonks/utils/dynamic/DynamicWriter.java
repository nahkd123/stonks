package io.github.nahkd123.stonks.utils.dynamic;

import java.io.IOException;

public interface DynamicWriter {
	void beginObject() throws IOException;

	void nextObjectKey(String key) throws IOException;

	void endObject() throws IOException;

	void beginArray() throws IOException;

	void endArray() throws IOException;

	void nextNumber(Number number) throws IOException;

	void nextString(String string) throws IOException;

	void nextBoolean(boolean bool) throws IOException;

	void nextNull() throws IOException;
}
